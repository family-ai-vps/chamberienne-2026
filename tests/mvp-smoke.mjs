import fs from 'node:fs';
import assert from 'node:assert/strict';
import vm from 'node:vm';

const html=fs.readFileSync(new URL('../index.html',import.meta.url),'utf8');
const script=html.match(/<script>([\s\S]*?)<\/script>/)?.[1];
assert.ok(script,'Script embarqué présent');
new vm.Script(script,{filename:'index.html'});
const raw=script.match(/const DATA=(\{[\s\S]*?\});/);
assert.ok(raw,'Données embarquées présentes');
const data=JSON.parse(raw[1]);
assert.equal(data.people.length,245,'245 bénévoles fictifs attendus');
assert.equal(data.posts.length,78,'78 postes attendus');
assert.equal(data.people.reduce((n,p)=>n+p.missions.length,0),287,'287 affectations attendues');
assert.equal(new Set(data.people.map(p=>p.id)).size,data.people.length,'IDs personnes uniques');
assert.ok(data.people.every(p=>Array.isArray(p.missions)&&Array.isArray(p.sources)),'Schéma personnes');
assert.ok(html.includes('background:#ff6568!important'),'Bouton secours rouge');
assert.ok(html.includes('CONTACTER LES SECOURS (FFSS)'),'Bouton secours');
assert.ok(html.includes('CONTACTER L’ORGANISATION'),'Bouton organisation');
assert.ok(html.includes('function submitSearch(input)'),'Recherche déclenchée à la validation');
assert.equal((html.match(/oninput="filter=/g)||[]).length,0,'Pas de filtrage à chaque frappe');
assert.ok(html.includes('🔎 Rechercher'),'Bouton de validation recherche');
assert.ok(html.includes("if(!t){alert("),'Incident non vide sans minimum de longueur');
assert.ok(html.includes('function volunteerPeople()'),'Choix des bénévoles');
assert.ok(html.includes('function incidents()'),'Gestion incidents');
assert.ok(html.includes('function requests()'),'Gestion renforts');
assert.ok(html.includes('function materials()'),'Gestion matériel');
assert.ok(html.includes('function newsScreen()'),'Infos course');
assert.ok(!html.includes('refreshSearchResults'),'Code mort de recherche supprimé');
assert.ok(!html.includes('keepFocus'),'Code mort de focus supprimé');
console.log('OK : syntaxe JS, intégrité données, invariants MVP et nettoyage statique.');
